-- Run once in the Supabase SQL Editor, or use python3 server.py --init-db.
-- Private schema: the browser continues to use the authenticated Python API.
BEGIN;
CREATE SCHEMA IF NOT EXISTS iit_voice;
REVOKE ALL ON SCHEMA iit_voice FROM PUBLIC;
SET LOCAL search_path TO iit_voice;

CREATE TABLE IF NOT EXISTS offices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('student', 'validator', 'admin', 'office')),
  affiliation TEXT NOT NULL,
  verified INTEGER NOT NULL DEFAULT 0 CHECK (verified IN (0, 1)),
  active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  created_at TEXT NOT NULL,
  is_demo INTEGER NOT NULL DEFAULT 0 CHECK (is_demo IN (0, 1)),
  office_id BIGINT REFERENCES offices(id)
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  csrf TEXT NOT NULL,
  expires DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS routing (
  category TEXT PRIMARY KEY,
  office_id BIGINT NOT NULL REFERENCES offices(id)
);
CREATE TABLE IF NOT EXISTS reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_id BIGINT NOT NULL REFERENCES users(id),
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  category TEXT NOT NULL,
  categories TEXT NOT NULL DEFAULT '[]',
  location TEXT NOT NULL,
  location_details TEXT NOT NULL DEFAULT '',
  indoor_location TEXT NOT NULL DEFAULT '{}',
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  priority TEXT NOT NULL DEFAULT 'normal',
  status TEXT NOT NULL DEFAULT 'submitted',
  visibility TEXT NOT NULL DEFAULT 'restricted',
  public_title TEXT NOT NULL DEFAULT '',
  public_summary TEXT NOT NULL DEFAULT '',
  office_id BIGINT REFERENCES offices(id),
  assigned_to BIGINT REFERENCES users(id),
  duplicate_of BIGINT REFERENCES reports(id),
  evidence_round INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES reports(id),
  actor_id BIGINT NOT NULL REFERENCES users(id),
  kind TEXT NOT NULL,
  message TEXT NOT NULL,
  internal INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS attachments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES reports(id),
  content BYTEA NOT NULL,
  mime TEXT NOT NULL,
  filename TEXT NOT NULL DEFAULT '',
  metadata TEXT NOT NULL DEFAULT '{}',
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS photo_analyses (
  token TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  photo_hash TEXT NOT NULL,
  metadata TEXT NOT NULL,
  created_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  report_id BIGINT REFERENCES reports(id),
  message TEXT NOT NULL,
  is_read INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT REFERENCES users(id),
  action TEXT NOT NULL,
  entity TEXT NOT NULL,
  detail TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS login_limits (
  key TEXT PRIMARY KEY,
  attempts INTEGER NOT NULL,
  start DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS reports_visibility ON reports(visibility, status);
CREATE INDEX IF NOT EXISTS reports_reporter ON reports(reporter_id);
CREATE INDEX IF NOT EXISTS reports_office ON reports(office_id, status);
CREATE INDEX IF NOT EXISTS events_report ON events(report_id);
CREATE INDEX IF NOT EXISTS attachments_report ON attachments(report_id);
CREATE INDEX IF NOT EXISTS notifications_user ON notifications(user_id, id);

-- Defense in depth: no browser Data API policies. The trusted database owner
-- connects from Python and the existing application checks every role/action.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE offices ENABLE ROW LEVEL SECURITY;
ALTER TABLE routing ENABLE ROW LEVEL SECURITY;
ALTER TABLE reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE events ENABLE ROW LEVEL SECURITY;
ALTER TABLE attachments ENABLE ROW LEVEL SECURITY;
ALTER TABLE photo_analyses ENABLE ROW LEVEL SECURITY;
ALTER TABLE notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit ENABLE ROW LEVEL SECURITY;
ALTER TABLE login_limits ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA iit_voice FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA iit_voice FROM PUBLIC;
COMMIT;
